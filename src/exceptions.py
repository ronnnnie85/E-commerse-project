from typing import Any


class ProductError(Exception):
    """Базовое исключение для ошибок, связанных с продуктами."""

    def __init__(self, *args: Any, **kwargs: Any) -> None:
        """
        Инициализирует исключение с сообщением об ошибке.

        Args:
            *args: Позиционные аргументы. Если передан хотя бы один аргумент,
                   используется первый аргумент как сообщение об ошибке.
            **kwargs: Именованные аргументы.
        """
        super().__init__(args[0] if args else "Ошибка добавления продукта")


class ProductTypeError(ProductError):
    """Исключение для случаев, когда передан продукт неправильного типа."""

    def __init__(self, *args: Any, **kwargs: Any) -> None:
        """
        Инициализирует исключение с сообщением о неверном типе продукта.

        Args:
            *args: Позиционные аргументы. Если передан хотя бы один аргумент,
                   используется первый аргумент как сообщение об ошибке.
            **kwargs: Именованные аргументы.
        """
        super().__init__(args[0] if args else "Неправильный тип продукта")


class ProductZeroError(ProductError):
    """Исключение для случаев, когда количество продукта равно нулю."""

    def __init__(self, *args: Any, **kwargs: Any) -> None:
        """
        Инициализирует исключение с сообщением о нулевом количестве продукта.

        Args:
            *args: Позиционные аргументы. Если передан хотя бы один аргумент,
                   используется первый аргумент как сообщение об ошибке.
            **kwargs: Именованные аргументы.
        """
        super().__init__(args[0] if args else "Нулевое количество продукта")
